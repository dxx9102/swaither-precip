# viz of generated diffusion samples ensemble members for one choice of time step and lead, for one or 2 models
def Viz_DiffSamplesMosaicMultiLead(
    preds,
    pred_names=None,
    truth=None,
    lr=None,
    AIFS_inputs=None,
    index_time=0,
    lead_index=0,
    numSamples=4,
    selection="first",
    random_state=None,
    sample_indices=None,
):
    """
    Visualise diffusion ensemble samples from one or more models at a single lead time.

    Layout (numSamples=4, 2 models) — all columns equal width, perfect alignment:
    ──────────────────────────────────────────────────────────────────
                 │  Model A            │  Model B
    ─────────────┼─────────────────────┼─────────────────────────
     HR Truth    │  BC LR   #1   #2   │  BC LR   #1   #2
     AIFS Input  │          #3   #4   │          #3   #4
                 │  Q05   Median Q95  │  Q05   Median Q95
    ──────────────────────────────────────────────────────────────────
    """

    # ── Normalize inputs ──
    if not isinstance(preds, (list, tuple)):
        preds = [preds]
    n_models = len(preds)

    if pred_names is None:
        pred_names = [f"Model {i+1}" for i in range(n_models)]
    elif isinstance(pred_names, str):
        pred_names = [pred_names]
    assert len(pred_names) == n_models

    if not isinstance(lr, (list, tuple)):
        lr = [lr] * n_models
    assert len(lr) == n_models

    # ── Lead labels ──
    LEAD_LABELS = [
        "6h", "12h", "18h", "24h",
        "2 days", "3 days", "4 days", "5 days", "6 days",
    ]

    def get_lead_label(idx):
        return LEAD_LABELS[idx] if idx < len(LEAD_LABELS) else f"L{idx}"

    # ── Coordinates & extent ──
    lon_vals = lr[0].lon
    lat_vals = lr[0].lat
    extent = [
        float(lon_vals.min()), float(lon_vals.max()),
        float(lat_vals.min()), float(lat_vals.max()),
    ]

    # ── Colormap ──
    config = ColormapConfig()
    cmap_custom, norm_custom, clevs = config.cmap, config.norm, config.clevs

    # ── Time string ──
    def _format_time(value):
        if value is None:
            return "unknown time"
        try:
            arr = np.asarray(value)
            if np.issubdtype(arr.dtype, np.datetime64):
                return np.datetime_as_string(arr.astype("datetime64[s]"))
        except Exception:
            pass
        return str(value)

    t_val = truth.time[index_time].values if "time" in truth.coords else None
    t_str = _format_time(t_val)
    lead_label = get_lead_label(lead_index)

    # ── Shared data slices ──
    truth_arr = truth.values[index_time, :, :]
    aifs_arr = AIFS_inputs.sel(time=truth.time[index_time]).sel(
        prediction_delta=AIFS_inputs.prediction_delta[lead_index]
    ).total_precipitation_NoNeg.values

    # ── Per-model data ──
    all_lr_arrs = []
    all_members = []
    all_medians = []
    all_q05 = []
    all_q95 = []

    for m, pred in enumerate(preds):
        lr_arr = lr[m].sel(time=truth.time[index_time]).sel(
            prediction_delta=AIFS_inputs.prediction_delta[lead_index]
        ).precip6h_cumulative_capped.values
        all_lr_arrs.append(lr_arr)

        pred_arr = pred.values[:, index_time, lead_index, :, :]
        n_ens = pred_arr.shape[0]

        if sample_indices is not None:
            indices = list(sample_indices) if not isinstance(sample_indices, list) else sample_indices
        elif selection == "first":
            indices = list(range(min(numSamples, n_ens)))
        elif selection == "random":
            rng = np.random.default_rng(random_state)
            indices = sorted(rng.choice(n_ens, size=min(numSamples, n_ens), replace=False))
        elif selection == "top_error":
            diff = pred_arr - truth_arr[None, :, :]
            mse = np.mean(diff ** 2, axis=(1, 2))
            indices = list(np.argsort(mse)[-numSamples:][::-1])
        else:
            raise ValueError(f"Unknown selection: {selection}")

        all_members.append(pred_arr[indices])
        all_medians.append(np.median(pred_arr, axis=0))
        all_q05.append(np.quantile(pred_arr, 0.05, axis=0))
        all_q95.append(np.quantile(pred_arr, 0.95, axis=0))

    actual_n_samples = all_members[0].shape[0]
    samples_per_row = max(math.ceil(actual_n_samples / 2), 2)

    # 3 columns per model block: col0=BC/Q05, col1=#1/#3/Median, col2=#2/#4/Q95
    block_cols = 1 + samples_per_row  # needs to be >= 3

    # ── Grid ──
    n_data_cols = 1 + n_models * block_cols
    n_cols_total = n_data_cols + 1
    n_rows = 3

    # All columns equal width (except ref slightly wider, colorbar thin)
    width_ratios = [1.05] + [1] * (n_models * block_cols) + [0.05]
    height_ratios = [1, 1, 1]

    fig_width = 1.65 * n_data_cols + 0.6 
    fig_height = 1.7 * n_rows + 0.3 -1.5

    fig = plt.figure(figsize=(fig_width, fig_height), dpi=120)

    gs = GridSpec(
        nrows=n_rows,
        ncols=n_cols_total,
        figure=fig,
        width_ratios=width_ratios,
        height_ratios=height_ratios,
        wspace=0.005,
        hspace=0.0,
    )
    fig.subplots_adjust(left=0.02, right=0.96, top=0.91, bottom=0.01)

    # fig.suptitle(
    #     f"Final generated high resolution samples for {t_str}  —  Lead: {lead_label}",
    #     fontsize=12, y=1.1,
    # )

    # ── Helper ──
    im_ref = None
    all_axes = {}

    def make_ax(row, col, key=None):
        ax = fig.add_subplot(gs[row, col], projection=ccrs.PlateCarree())
        if key:
            all_axes[key] = ax
        return ax

    def plot_map(ax, data, title="", fontsize=8, bold=False, pad=1):
        nonlocal im_ref
        im = ax.imshow(
            data, origin="lower", extent=extent,
            cmap=cmap_custom, norm=norm_custom,
            transform=ccrs.PlateCarree(), interpolation="nearest",
        )
        ax.add_geometries(
            [switz_geom], ccrs.PlateCarree(),
            facecolor="none", edgecolor="k", linewidth=0.5,
        )
        if title:
            weight = "bold" if bold else "normal"
            ax.set_title(title, fontsize=fontsize, fontweight=weight, pad=pad)
        ax.axis("off")
        if im_ref is None:
            im_ref = im
        return im

    def hide(ax):
        ax.set_visible(False)

    # ── Reference column ──
    ax_truth = make_ax(0, 0, key="ref_r0")
    plot_map(ax_truth, truth_arr, f"HR Truth\n{t_str}\nLead: {lead_label}", fontsize=9, bold=False)

    hide(make_ax(1, 0, key="ref_r1"))

    ax_aifs = make_ax(2, 0, key="ref_r2")
    plot_map(ax_aifs, aifs_arr, "AIFS Input", fontsize=9, bold=True)

    # ── Model blocks ──
    for m in range(n_models):
        col_base = 1 + m * block_cols
        members = all_members[m]

        # Row 0: BC LR in col_base, samples #1 #2 in col_base+1, col_base+2
        ax_bc = make_ax(0, col_base, key=f"bc_{m}")
        plot_map(ax_bc, all_lr_arrs[m], "Bias Corrected", fontsize=8, bold=True)

        for j in range(samples_per_row):
            col = col_base + 1 + j
            ax = make_ax(0, col, key=f"s_{m}_r0_c{j}")
            if j < actual_n_samples:
                plot_map(ax, members[j], f"Sample #{j+1}", fontsize=7)
            else:
                hide(ax)

        # Row 1: empty under BC LR, samples #3 #4
        hide(make_ax(1, col_base, key=f"empty_{m}_r1"))

        for j in range(samples_per_row):
            idx = samples_per_row + j
            col = col_base + 1 + j
            ax = make_ax(1, col, key=f"s_{m}_r1_c{j}")
            if idx < actual_n_samples:
                plot_map(ax, members[idx], f"Sample #{idx+1}", fontsize=7)
            else:
                hide(ax)

        # Row 2: Q05 under BC LR, Median under #1/#3, Q95 under #2/#4
        stats = [
            (all_q05[m],     "Q05"),
            (all_medians[m], "Median"),
            (all_q95[m],     "Q95"),
        ]
        for j, (data, title) in enumerate(stats):
            col = col_base + j
            ax = make_ax(2, col, key=f"st_{m}_c{j}")
            plot_map(ax, data, title, fontsize=7, bold=True)

        # Hide extra columns in stats row if samples_per_row > 2
        for j in range(3, block_cols):
            col = col_base + j
            hide(make_ax(2, col, key=f"st_{m}_extra_{j}"))

        # Model name header
        ax_left_pos = all_axes[f"bc_{m}"].get_position()
        ax_right_pos = all_axes[f"s_{m}_r0_c{samples_per_row - 1}"].get_position()
        x_mid = 0.5 * (ax_left_pos.x0 + ax_right_pos.x1)
        y_top = ax_right_pos.y1 + 0.006
        fig.text(
            x_mid, y_top + 0.09, pred_names[m],
            fontsize=10, fontweight="bold", color="0.3",
            ha="center", va="bottom",
        )

    # ── Vertical separator: reference | models ──
    pos_ref = all_axes["ref_r0"].get_position()
    pos_bc0 = all_axes["bc_0"].get_position()
    vis_stats = [k for k in all_axes if k.startswith("st_") and all_axes[k].get_visible()]
    y_bottom = min(all_axes[k].get_position().y0 for k in vis_stats) - 0.003
    y_top_line = pos_ref.y1 + 0.003

    x_sep_ref = 0.5 * (pos_ref.x1 + pos_bc0.x0)
    fig.add_artist(mlines.Line2D(
        [x_sep_ref, x_sep_ref], [y_bottom, y_top_line],
        transform=fig.transFigure,
        color="grey", linewidth=1.0, linestyle="--", clip_on=False,
    ))

    # Vertical: between model blocks
    for m in range(1, n_models):
        prev_key = f"s_{m-1}_r0_c{samples_per_row - 1}"
        next_key = f"bc_{m}"
        x_prev = all_axes[prev_key].get_position().x1
        x_next = all_axes[next_key].get_position().x0
        x_sep = 0.5 * (x_prev + x_next)
        fig.add_artist(mlines.Line2D(
            [x_sep, x_sep], [y_bottom, y_top_line],
            transform=fig.transFigure,
            color="grey", linewidth=0.8, linestyle=":", clip_on=False,
        ))

    # ── Colorbar ──
    cbar_ax = fig.add_axes([0.965, 0.03, 0.010, 0.86])
    cbar = fig.colorbar(
        im_ref, cax=cbar_ax,
        boundaries=clevs, ticks=clevs[::2], extend="both",
    )
    cbar.set_label("6h Precip. (mm)", fontsize=9, fontweight="bold", labelpad=2)
    cbar.ax.tick_params(labelsize=7)

    plt.show()

    return fig


# viz of generated diffusion samples for one choice of time step, and for multiple leads, median through the ensemble members
def Viz_AllLeadsOverview(
    preds,
    pred_names=None,
    truth=None,
    lr=None,
    AIFS_inputs=None,
    index_time=0,
    *,
    pred_var="precip6h_cumulative_capped",
    truth_var="precip6h_cumulative_capped",
    lr_var="precip6h_cumulative_capped",
    aifs_var="total_precipitation_NoNeg",
    pred_reduce="median",
    member_index=0,
    max_leads=None,
    lead_indices=None,
    show_aifs=True,
    ncols=9,
):
    """
    Visualise predictions across all lead times for one or more models.

    Layout (2 models, 9 leads):
    ──────────────────────────────────────────────────────────────────────
             HR Truth  (empty) (empty) ...                        (row 0)
     AIFS  │  6h   12h   18h   24h   2d   3d   4d   5d   6d     (row 1)
    ── ── ─┼── ── ── ── ── ── ── ── ── ── ── ── ── ── ── ── ──
     BC LR │  ...                                                 (row 2)  Model A
     Pred  │  ...                                                 (row 3)
    ·······┼···················································
     BC LR │  ...                                                 (row 4)  Model B
     Pred  │  ...                                                 (row 5)
    ──────────────────────────────────────────────────────────────────────
    All row labels are vertical (rotated 90°) to save width.
    """

    # ── Normalize inputs to lists ──
    if not isinstance(preds, (list, tuple)):
        preds = [preds]
    n_models = len(preds)

    if pred_names is None:
        pred_names = [f"Model {i+1}" for i in range(n_models)]
    elif isinstance(pred_names, str):
        pred_names = [pred_names]
    assert len(pred_names) == n_models

    if not isinstance(lr, (list, tuple)):
        lr = [lr] * n_models
    assert len(lr) == n_models

    # ── Pick DataArrays if Datasets ──
    pred_das = [p[pred_var] if hasattr(p, "data_vars") else p for p in preds]
    truth_da = truth[truth_var] if hasattr(truth, "data_vars") else truth
    lr_das   = [l[lr_var] if hasattr(l, "data_vars") else l for l in lr]
    aifs_da  = AIFS_inputs[aifs_var] if hasattr(AIFS_inputs, "data_vars") else AIFS_inputs

    # ── Infer spatial dims ──
    core = {"ensemble", "time", "lead"}
    pred_spatial = [d for d in pred_das[0].dims if d not in core]
    if len(pred_spatial) != 2:
        raise ValueError(f"Expected 2 spatial dims, got {pred_spatial}")
    y_dim, x_dim = pred_spatial

    # ── Remap LR/AIFS to pred grid ──
    def _infer_spatial(da):
        ignore = {"time", "prediction_delta"}
        return [d for d in da.dims if d not in ignore]

    def _to_pred_grid(da):
        sp = _infer_spatial(da)
        if len(sp) != 2:
            raise ValueError(f"Expected 2 spatial dims, got {sp}")
        out = da.rename({sp[0]: y_dim, sp[1]: x_dim})
        if y_dim in pred_das[0].coords:
            out = out.assign_coords({y_dim: pred_das[0][y_dim]})
        if x_dim in pred_das[0].coords:
            out = out.assign_coords({x_dim: pred_das[0][x_dim]})
        return out

    lr_on_preds = [_to_pred_grid(l) for l in lr_das]
    aifs_on_pred = _to_pred_grid(aifs_da)

    # ── Lead list ──
    n_leads_total = pred_das[0].sizes["lead"]
    if lead_indices is None:
        if max_leads is None:
            lead_indices = np.arange(n_leads_total)
        else:
            lead_indices = np.arange(min(max_leads, n_leads_total))
    else:
        lead_indices = np.asarray(lead_indices, dtype=int)

    n_show = len(lead_indices)
    ncols = min(ncols, n_show)

    LEAD_LABELS = ["6h", "12h", "18h", "24h", "2d", "3d", "4d", "5d", "6d"]

    def get_lead_label(idx):
        return LEAD_LABELS[idx] if idx < len(LEAD_LABELS) else f"L{idx}"

    # ── Coordinates & colormap ──
    lon_vals = lr[0].lon
    lat_vals = lr[0].lat
    extent = [float(lon_vals.min()), float(lon_vals.max()),
              float(lat_vals.min()), float(lat_vals.max())]

    config = ColormapConfig()
    cmap_custom, norm_custom, clevs = config.cmap, config.norm, config.clevs

    # ── Time ──
    def _format_time(value):
        if value is None:
            return "unknown time"
        try:
            arr = np.asarray(value)
            if np.issubdtype(arr.dtype, np.datetime64):
                return np.datetime_as_string(arr.astype("datetime64[s]"))
        except Exception:
            pass
        return str(value)

    truth_slice = truth_da.isel(time=index_time).transpose(y_dim, x_dim)
    truth_arr = truth_slice.values
    t_val = truth_slice.coords["time"].values if "time" in truth_slice.coords else None
    t_str = _format_time(t_val)
    t_for_sel = truth_da["time"].isel(time=index_time).values
    pdeltas = AIFS_inputs["prediction_delta"].values

    # ── Reduce pred ensemble per model ──
    def reduce_pred(pred_da):
        pred_t = pred_da.isel(time=index_time).transpose("ensemble", "lead", y_dim, x_dim).values
        if pred_reduce == "median":
            return np.median(pred_t, axis=0)
        elif pred_reduce == "mean":
            return np.mean(pred_t, axis=0)
        elif pred_reduce == "q05":
            return np.quantile(pred_t, 0.05, axis=0)
        elif pred_reduce == "q95":
            return np.quantile(pred_t, 0.95, axis=0)
        elif pred_reduce == "member":
            return pred_t[member_index, ...]
        else:
            raise ValueError(f"Unknown pred_reduce: {pred_reduce}")

    all_pred_red = [reduce_pred(pd)[lead_indices, :, :] for pd in pred_das]

    reduce_labels = {
        "median": "Median", "mean": "Mean",
        "q05": "Q05", "q95": "Q95",
        "member": f"Member #{member_index+1}",
    }
    pred_title = reduce_labels.get(pred_reduce, pred_reduce)

    # ── LR / AIFS maps per lead ──
    def get_lr_maps(lr_on_pred):
        maps = []
        for li in lead_indices:
            arr = (lr_on_pred.sel(time=t_for_sel)
                   .sel(prediction_delta=pdeltas[li])
                   .transpose(y_dim, x_dim).values)
            maps.append(arr)
        return np.stack(maps, axis=0)

    all_lr_maps = [get_lr_maps(lp) for lp in lr_on_preds]

    aifs_maps = None
    if show_aifs:
        a_maps = []
        for li in lead_indices:
            arr = (aifs_on_pred.sel(time=t_for_sel)
                   .sel(prediction_delta=pdeltas[li])
                   .transpose(y_dim, x_dim).values)
            a_maps.append(arr)
        aifs_maps = np.stack(a_maps, axis=0)

    # ── Layout ──
    # Row 0: HR Truth (col 0 only, rest empty)
    # Row 1: AIFS across leads (if show_aifs)
    # Then per model: 2 rows (BC LR + Prediction)
    truth_rows = 1
    aifs_rows = 1 if show_aifs else 0
    rows_per_model = 2
    total_rows = truth_rows + aifs_rows + n_models * rows_per_model

    # No wide left label column — just the lead columns + colorbar
    n_cols_total = ncols + 1  # lead cols + colorbar

    fig_width = 2.2 * ncols + 0.6 -1
    fig_height = 1.7 * total_rows + 0.3 -1

    fig = plt.figure(figsize=(fig_width, fig_height), dpi=120)

    width_ratios = [1.0] * ncols + [0.05]
    height_ratios = [1] * total_rows

    gs = GridSpec(
        nrows=total_rows,
        ncols=n_cols_total,
        figure=fig,
        width_ratios=width_ratios,
        height_ratios=height_ratios,
        wspace=0.00,
        hspace=0.0,
    )
    fig.subplots_adjust(left=0.06, right=0.97, top=0.96, bottom=0.01)

    # ── Helper ──
    im_ref = None
    all_axes = {}

    def make_ax(row, col, key=None):
        ax = fig.add_subplot(gs[row, col], projection=ccrs.PlateCarree())
        if key:
            all_axes[key] = ax
        return ax

    def plot_map(ax, data, title="", fontsize=8, bold=False, pad=1):
        nonlocal im_ref
        im = ax.imshow(
            data, origin="lower", extent=extent,
            cmap=cmap_custom, norm=norm_custom,
            transform=ccrs.PlateCarree(), interpolation="nearest",
        )
        ax.add_geometries(
            [switz_geom], ccrs.PlateCarree(),
            facecolor="none", edgecolor="k", linewidth=0.5,
        )
        if title:
            weight = "bold" if bold else "normal"
            ax.set_title(title, fontsize=fontsize, fontweight=weight, pad=pad)
        ax.axis("off")
        if im_ref is None:
            im_ref = im
        return im

    def hide(ax):
        ax.set_visible(False)

    # ── Row 0: HR Truth in col 0, rest empty ──
    ax_truth = make_ax(0, 0, key="truth")
    plot_map(ax_truth, truth_arr, f"HR Truth\n{t_str}", fontsize=9, bold=False)
    for c in range(1, ncols):
        hide(make_ax(0, c, key=f"empty_r0_{c}"))

    # ── Row 1: AIFS across leads ──
    row_aifs = truth_rows
    if show_aifs:
        for i in range(n_show):
            li = int(lead_indices[i])
            ax = make_ax(row_aifs, i, key=f"aifs_{i}")
            plot_map(ax, aifs_maps[i], get_lead_label(li), fontsize=7)

        # Rotated label on the left
        ax_first = all_axes["aifs_0"]
        pos = ax_first.get_position()
        y_mid = 0.5 * (pos.y0 + pos.y1)
        fig.text(0.04, y_mid, "AIFS\nInput",
                 fontsize=9, fontweight="bold", color="0.35",
                 ha="center", va="center", rotation=90)

    # ── Model blocks ──
    for m in range(n_models):
        row_base = truth_rows + aifs_rows + m * rows_per_model
        row_lr = row_base
        row_pred = row_base + 1

        # BC LR across leads
        for i in range(n_show):
            li = int(lead_indices[i])
            ax = make_ax(row_lr, i, key=f"lr_{m}_{i}")
            # Lead labels only on first model if no AIFS row
            label = get_lead_label(li) if (m == 0 and not show_aifs) else ""
            plot_map(ax, all_lr_maps[m][i], label, fontsize=7)

        # Predictions across leads
        for i in range(n_show):
            ax = make_ax(row_pred, i, key=f"pred_{m}_{i}")
            plot_map(ax, all_pred_red[m][i], "", fontsize=7)

        # Rotated labels on the left
        ax_lr_first = all_axes[f"lr_{m}_0"]
        ax_pred_first = all_axes[f"pred_{m}_0"]

        # Model name centered across both rows
        y_mid_model = 0.5 * (ax_lr_first.get_position().y1
                              + ax_pred_first.get_position().y0)
        fig.text(0.04, y_mid_model, pred_names[m],
                 fontsize=10, fontweight="bold", color="0.35",
                 ha="center", va="center", rotation=90)

        # BC LR label
        pos_lr = ax_lr_first.get_position()
        fig.text(0.05, 0.5 * (pos_lr.y0 + pos_lr.y1), "Bias Corrected",
                 fontsize=8, fontstyle="italic", color="0.45",
                 ha="center", va="center", rotation=90)

        # Prediction label
        pos_pred = ax_pred_first.get_position()
        fig.text(0.05, 0.5 * (pos_pred.y0 + pos_pred.y1), pred_title + " sample",
                 fontsize=8, fontstyle="italic", color="0.45",
                 ha="center", va="center", rotation=90)

    # ── Horizontal separator: AIFS | first model ──
    if show_aifs:
        ax_above = all_axes[f"aifs_0"]
        ax_below = all_axes[f"lr_0_0"]
        y_sep = 0.5 * (ax_above.get_position().y0 + ax_below.get_position().y1)
        x_left = ax_above.get_position().x0 - 0.005
        x_right = all_axes[f"aifs_{n_show - 1}"].get_position().x1 + 0.005
        fig.add_artist(mlines.Line2D(
            [x_left, x_right], [y_sep, y_sep],
            transform=fig.transFigure,
            color="grey", linewidth=1.0, linestyle="--", clip_on=False,
        ))

    # ── Horizontal separators between model blocks ──
    for m in range(1, n_models):
        ax_above = all_axes[f"pred_{m-1}_0"]
        ax_below = all_axes[f"lr_{m}_0"]
        y_sep = 0.5 * (ax_above.get_position().y0 + ax_below.get_position().y1)
        x_left = ax_above.get_position().x0 - 0.005
        x_right = all_axes[f"pred_{m-1}_{n_show - 1}"].get_position().x1 + 0.005
        fig.add_artist(mlines.Line2D(
            [x_left, x_right], [y_sep, y_sep],
            transform=fig.transFigure,
            color="grey", linewidth=0.8, linestyle=":", clip_on=False,
        ))

    # ── Colorbar ──
    cbar_ax = fig.add_subplot(gs[:, -1])
    cbar = fig.colorbar(
        im_ref, cax=cbar_ax,
        boundaries=clevs, ticks=clevs[::2], extend="both",
    )
    cbar.set_label("6h Precip. (mm)", fontsize=9, fontweight="bold", labelpad=2)
    cbar.ax.tick_params(labelsize=7)

    plt.show()
    return fig
    

