class ColormapConfig:
    def __init__(self):
        self.cmap = None
        self.norm = None
        self.clevs = None

        self.build_colormap()

    def build_colormap(self):
        # Define the colormap boundaries and colors
        # color_list = ['lightgrey', 'lightskyblue', 'blue', 'yellow', 'orange', 'red', 'darkred']

        # color_list = ['lightgrey', 'lightskyblue', 'blue', 'yellow', 'orange', 'red', 'darkred']
        #self.clevs = [0.000001, 0.01, 0.1, 0.5, 1.5, 2.5, 4, 6, 10]  # mm/hr

        color_list = ["lightblue", "dodgerblue", "blue", "navy", "yellow", "orange", "green", "orangered", "red", "darkred"]

        self.clevs = [0.1, 0.2, 0.5, 1, 2, 3, 5, 7, 10, 30, 60]  # mm/hr

        # Create a ListedColormap object with the defined colors
        self.cmap = colors.ListedColormap(color_list)
        self.cmap.name = "Custom Colormap"

        # Set the color for values above the maximum level
        self.cmap.set_over("darkmagenta")
        # Set the color for values below the minimum level
        self.cmap.set_under("none")
        # Set the color for missing values
        self.cmap.set_bad("gray", alpha=0.5)

        # Create a BoundaryNorm object to normalize the data values to the colormap boundaries
        self.norm = colors.BoundaryNorm(self.clevs, self.cmap.N)



# plot how time steps are distributed in validation set, regarding the months and seasons 
def PlotDistribValSet(val_times, img_name="val_distrib.png"):

    # ── 1.  YOUR TIMESTEPS ──────────────────────────────────────────────────────
    timestamps = val_times

    # ── 2.  PARSE ────────────────────────────────────────────────────────────────
    dts = [datetime.datetime.fromtimestamp(
            int(np.datetime64(t, 's').view('int64')),
            tz=datetime.timezone.utc)
        for t in timestamps]

    months  = np.array([d.month for d in dts])   # 1-12
    hours   = np.array([d.hour  for d in dts])   # 0, 6, 12, or 18

    def month_to_season(m):
        if m in (12, 1, 2):  return 'DJF'
        if m in (3, 4, 5):   return 'MAM'
        if m in (6, 7, 8):   return 'JJA'
        return 'SON'

    seasons = np.array([month_to_season(m) for m in months])


    # ── 3.  COUNT ────────────────────────────────────────────────────────────────
    MONTH_NAMES   = ['Jan','Feb','Mar','Apr','May','Jun',
                    'Jul','Aug','Sep','Oct','Nov','Dec']
    SEASON_ORDER  = ['DJF', 'MAM', 'JJA', 'SON']
    SEASON_LABELS = ['Winter\n(DJF)', 'Spring\n(MAM)', 'Summer\n(JJA)', 'Autumn\n(SON)']

    month_counts  = np.array([(months == m).sum() for m in range(1, 13)])
    season_counts = np.array([(seasons == s).sum() for s in SEASON_ORDER])

    # Time-of-day: consider all possible 6-hourly slots, keep only those present.
    # This avoids a matplotlib crash when a zero-count slice is passed to pie().
    ALL_HOURS    = [0, 6, 12, 18]
    ALL_LABELS   = ['00:00 UTC', '06:00 UTC', '12:00 UTC', '18:00 UTC']
    ALL_COLORS_T = ['#5b8dee', '#f0a840', '#f06892', '#78c880']

    hour_tuples  = [(lbl, int((hours == h).sum()), col)
                    for h, lbl, col in zip(ALL_HOURS, ALL_LABELS, ALL_COLORS_T)
                    if (hours == h).sum() > 0]   # drop zero-count slots

    time_labels  = [t[0] for t in hour_tuples]
    time_counts  = np.array([t[1] for t in hour_tuples])
    TIME_COLORS  = [t[2] for t in hour_tuples]

    N = len(dts)
    expected_month  = N / 12
    expected_season = N / 4
    expected_time   = N / len(time_counts)   # ideal = equal split among present hours


    # ── 4.  STYLE ────────────────────────────────────────────────────────────────
    BG      = 'white'
    PANEL   = 'white'
    GRID    = '#dddddd'
    TEXT    = 'black'
    SUBTEXT = '#444444'
    ACCENT  = '#222222'

    MONTH_COLORS = [
        '#4a9eff','#5aaeff','#69c3a0','#78d9a0','#98e8b0','#b8f0c0',
        '#f0c060','#e8a040','#d08040','#c06030','#8090c0','#5070b0'
    ]
    SEASON_COLORS = ['#6090d0','#78c880','#f0a840','#d06848']

    plt.rcParams.update({
        'figure.facecolor':  BG,
        'axes.facecolor':    PANEL,
        'axes.edgecolor':    '#bbbbbb',
        'axes.labelcolor':   TEXT,
        'xtick.color':       TEXT,
        'ytick.color':       TEXT,
        'text.color':        TEXT,
        'grid.color':        GRID,
        'grid.linestyle':    '--',
        'grid.linewidth':    0.6,
        'font.family':       'DejaVu Sans',
    })


    # ── 5.  FIGURE ───────────────────────────────────────────────────────────────
    fig = plt.figure(figsize=(14, 10), facecolor=BG)
    fig.suptitle(
        f'Temporal Distribution Analysis  ·  {N} timesteps',
        fontsize=16, fontweight='bold', color=TEXT, y=0.98
    )

    gs = GridSpec(2, 2, figure=fig, hspace=0.45, wspace=0.35,
                left=0.07, right=0.97, top=0.92, bottom=0.07)

    ax_month  = fig.add_subplot(gs[0, :])   # full top row
    ax_season = fig.add_subplot(gs[1, 0])   # bottom left
    ax_time   = fig.add_subplot(gs[1, 1])   # bottom right


    # ── 5a. MONTHLY ───────────────────────────────────────────────────────────────
    x = np.arange(12)
    bars = ax_month.bar(x, month_counts, color=MONTH_COLORS, width=0.65,
                        zorder=3, edgecolor='none')
    ax_month.axhline(expected_month, color=ACCENT, lw=1.5, ls='--',
                    label=f'Ideal uniform ({expected_month:.1f}/month)', zorder=4)

    for i, (bar, count) in enumerate(zip(bars, month_counts)):
        dev = count - expected_month
        pct = dev / expected_month * 100
        color = '#2a9d2a' if abs(pct) < 5 else ('#e07800' if dev > 0 else '#cc2222')
        ax_month.text(bar.get_x() + bar.get_width()/2, count + 0.15,
                    f'{pct:+.0f}%', ha='center', va='bottom',
                    fontsize=8, color=color, fontweight='bold')

    ax_month.set_xticks(x)
    ax_month.set_xticklabels(MONTH_NAMES, fontsize=10)
    ax_month.set_ylabel('Step count', fontsize=10)
    ax_month.set_title('Monthly Distribution', fontsize=12, fontweight='bold',
                    color=TEXT, pad=8)
    ax_month.legend(fontsize=9, framealpha=0.2, facecolor=PANEL,
                    edgecolor=GRID, labelcolor=TEXT)
    ax_month.yaxis.grid(True, zorder=0)
    ax_month.set_axisbelow(True)
    ax_month.spines[['top','right','left','bottom']].set_visible(False)


    # ── 5b. SEASONAL ──────────────────────────────────────────────────────────────
    xs = np.arange(4)
    ax_season.bar(xs, season_counts, color=SEASON_COLORS, width=0.55,
                zorder=3, edgecolor='none')
    ax_season.axhline(expected_season, color=ACCENT, lw=1.5, ls='--',
                    label=f'Ideal ({expected_season:.1f})', zorder=4)

    for i, (count, c) in enumerate(zip(season_counts, SEASON_COLORS)):
        pct = (count / N * 100)
        ax_season.text(i, count + 0.2, f'{count}\n({pct:.1f}%)',
                    ha='center', va='bottom', fontsize=9, color=c, fontweight='bold')

    ax_season.set_xticks(xs)
    ax_season.set_xticklabels(SEASON_LABELS, fontsize=9)
    ax_season.set_ylabel('Step count', fontsize=10)
    ax_season.set_title('Seasonal Distribution', fontsize=12, fontweight='bold',
                        color=TEXT, pad=8)
    ax_season.legend(fontsize=9, framealpha=0.2, facecolor=PANEL,
                    edgecolor=GRID, labelcolor=TEXT)
    ax_season.yaxis.grid(True, zorder=0)
    ax_season.set_axisbelow(True)
    ax_season.spines[['top','right','left','bottom']].set_visible(False)


    # ── 5c. TIME OF DAY (pie) ─────────────────────────────────────────────────────
    wedge_props = dict(width=0.45, edgecolor=BG, linewidth=2)
    wedges, texts, autotexts = ax_time.pie(
        time_counts,
        labels=time_labels,           # only labels for hours that actually exist
        colors=TIME_COLORS,
        autopct='%1.1f%%',
        startangle=90,
        wedgeprops=wedge_props,
        pctdistance=0.75,
        textprops={'color': TEXT, 'fontsize': 10}
    )
    for at in autotexts:
        at.set_fontsize(9)
        at.set_color('white')
        at.set_fontweight('bold')

    # Centre annotation: balance check across present slots
    max_dev = max(abs(c - expected_time) for c in time_counts)
    balance_txt = 'Balanced ✓' if max_dev <= 2 else f'Max Δ = {int(max_dev)}'
    ax_time.text(0, 0, balance_txt, ha='center', va='center',
                fontsize=9, color=TEXT, fontweight='bold')

    ax_time.set_title('Time of Day Split', fontsize=12, fontweight='bold',
                    color=TEXT, pad=8)

    patches = [mpatches.Patch(color=TIME_COLORS[i],
                            label=f'{time_labels[i]}: {time_counts[i]} steps')
            for i in range(len(time_counts))]
    ax_time.legend(handles=patches, fontsize=9, framealpha=0.2,
                facecolor=PANEL, edgecolor=GRID, labelcolor=TEXT,
                loc='lower center', bbox_to_anchor=(0.5, -0.12))



    # ── 6.  SAVE ─────────────────────────────────────────────────────────────────
    out = img_name
    plt.savefig(out, dpi=150, bbox_inches='tight', facecolor=BG)
    print(f'Saved → {out}')
    plt.show()


